// The sidebar of the Starlight site (site-starlight, design D6), built from
// the pages in src/content/docs/docs/ before Astro reads its config:
//
// * one group per chapter (a directory below docs/), in the order of the
//   chapters' sidebar.order (Hugo's weight), labelled with the title of the
//   chapter's index page;
// * in a group the chapter's index page first, then its pages and its
//   sections (a directory with an index page: a group of its own, labelled
//   and ordered the same way), sorted as Hugo sorts a section: by
//   sidebar.order, pages without one last, then by title;
// * the reference groups (the command reference of task 5.2 and the
//   library fix pages, one page per library) collapsed: Starlight opens a
//   collapsed group on the pages it holds.
//
// Starlight's own autogenerated groups are labelled with the directory's
// name and place a directory's index page among its pages by its order,
// hence the groups are written out here. The pages of the command
// reference come from a content loader (src/lib/cmdref.mjs), not from
// files: their groups list the section's index page and then its pages by
// title, as Hugo does (Starlight's autogenerate would sort them by their
// path, which for the AmigaOS pages is not their title's order).
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import YAML from "yaml";
import { sectionPages } from "./cmdref.mjs";

/** The directories whose pages the command reference loader adds */
const LOADED = new Set(["docs/libraries/commands", "docs/libraries/amigaos", "docs/libraries/userlibs"]);
/** The groups shown collapsed: the reference and the library fix pages */
const COLLAPSED = new Set([
  ...LOADED,
  "docs/compared-with-original/libraries/commands",
  "docs/compared-with-original/libraries/userlibs",
]);

const PAGE = /\.mdx?$/;

/** The front matter of a page file */
function frontMatter(file) {
  const m = readFileSync(file, "utf8").match(/^---\n([\s\S]*?)\n---\n/);
  return (m && YAML.parse(m[1])) || {};
}

/** The index page of a directory, or undefined */
const indexOf = (dir) => readdirSync(dir).find((n) => /^index\.mdx?$/.test(n));

/**
 * Whether the directory dir with the index page index is a section (Hugo's
 * branch bundle: it holds pages or sections, or is filled by the loader)
 * and not a page with its images (Hugo's leaf bundle, an index.md beside
 * files that are no pages)
 */
const isSection = (dir, index, slug) =>
  LOADED.has(slug) ||
  readdirSync(dir).some((n) => n !== index && (PAGE.test(n) || (statSync(join(dir, n)).isDirectory() && indexOf(join(dir, n)))));

/** Hugo's order of a section's pages: weight (none last), then title */
function byWeight(a, b) {
  const wa = a.order ?? Infinity;
  const wb = b.order ?? Infinity;
  if (wa !== wb) return wa < wb ? -1 : 1;
  return a.title.localeCompare(b.title, "en");
}

/**
 * The sidebar entry of a directory below the docs root (slug "docs/a/b"):
 * {order, title, item} with item a Starlight sidebar group.
 */
function section(root, slug) {
  const dir = join(root, slug);
  const index = indexOf(dir);
  if (!index) throw new Error(`sidebar: ${slug} has no index page`);
  const fm = frontMatter(join(dir, index));
  const group = { label: fm.title, items: [] };
  if (COLLAPSED.has(slug)) group.collapsed = true;
  if (LOADED.has(slug)) group.items.push({ slug }, ...sectionPages(slug.split("/").pop()).map((p) => ({ slug: p.id })));
  else {
    const children = [];
    const page = (file, s) => {
      const c = frontMatter(file);
      children.push({ order: c.sidebar?.order, title: c.title, item: { slug: s } });
    };
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) {
        const i = indexOf(p);
        if (!i) continue;
        // a page with its images (Hugo's leaf bundle) or a section
        if (isSection(p, i, `${slug}/${name}`)) children.push(section(root, `${slug}/${name}`));
        else page(join(p, i), `${slug}/${name}`);
      } else if (PAGE.test(name) && name !== index) page(p, `${slug}/${name.replace(PAGE, "")}`);
    }
    group.items.push({ slug }, ...children.sort(byWeight).map((c) => c.item));
  }
  return { order: fm.sidebar?.order, title: fm.title, item: group };
}

/** Starlight's sidebar config for the pages below root/docs (root: src/content/docs) */
export function sidebar(root) {
  return readdirSync(join(root, "docs"))
    .filter((name) => statSync(join(root, "docs", name)).isDirectory())
    .map((name) => section(root, `docs/${name}`))
    .sort(byWeight)
    .map((c) => c.item);
}
