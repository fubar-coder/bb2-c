/*
 * refcheck data, data-ref - data of a C build against the reference build
 * of the assembler original (see checkdata.h).
 *
 *   refcheck data [-v|-q] TABLE REFDATA CBUILD [INTENDED]
 *   e.g. refcheck data programs/ted/checkdata.tsv tests/data/ted-checkdata.txt ted.sym
 *   refcheck data-ref TABLE LISTING REFERENCE -o REFDATA
 *   e.g. refcheck data-ref programs/ted/checkdata.tsv ref/ted.lst ref/ted -o ted-checkdata.txt
 *
 * REFDATA: the reference bytes of the table's ranges, written by data-ref
 * from the reference build (its listing and load file), so data needs no
 * reference build.  INTENDED: the list of intended differences (fixed
 * original bugs, "CSYM<TAB>#NNN<TAB>NOTE" per line): those checks may
 * differ, and each of them must (a stale entry fails).
 *
 * data prints the failed checks and a summary (-q: only if a check failed,
 * -v: every check); exit status 1 if a check failed or an entry is stale.
 */
#define _XOPEN_SOURCE 700       /* open_memstream */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <memory>
#include <string>
#include <vector>
#include "cli.hpp"
extern "C" {
#include "checkdata.h"
}
#include "refcheck.h"

static char *read_all(const char *path, size_t *len)
{
    FILE *f = fopen(path, "rb");
    char *s = NULL;
    long n;

    if (!f)
        return NULL;
    if (!fseek(f, 0, SEEK_END) && (n = ftell(f)) >= 0 && !fseek(f, 0, SEEK_SET)
        && (s = (char *)malloc((size_t)n + 1)) && fread(s, 1, (size_t)n, f) == (size_t)n) {
        s[n] = 0;
        *len = (size_t)n;
    } else {
        free(s);
        s = NULL;
    }
    fclose(f);
    return s;
}

static const char *me; /* "refcheck data", the prefix of the messages */

/* read and parse the table; 0 = ok */
static int read_table(const std::string &path, struct checkdata_table *t)
{
    char err[200], *text;
    size_t len;

    if (!(text = read_all(path.c_str(), &len))) {
        fprintf(stderr, "%s: cannot read %s\n", me, path.c_str());
        return 1;
    }
    if (checkdata_table_parse(text, len, t, err, sizeof err)) {
        fprintf(stderr, "%s: %s: %s\n", me, path.c_str(), err);
        free(text);
        return 1;
    }
    free(text);
    return 0;
}

struct data_options {
    bool verbose = false, quiet = false;
    std::string table, refdata, cbuild, intended;
};

static int run(const data_options &o)
{
    struct checkdata_table table;
    struct checkdata_intended intended = { NULL, 0 };
    struct checkdata_ref refdata;
    struct loadfile c;
    char err[200], *text, *report = NULL;
    size_t len, reportlen = 0;
    FILE *out;
    long bad;
    const bool with_intended = !o.intended.empty();

    if (read_table(o.table, &table))
        return 1;
    if (with_intended) {
        if (!(text = read_all(o.intended.c_str(), &len))) {
            fprintf(stderr, "%s: cannot read %s\n", me, o.intended.c_str());
            return 1;
        }
        if (checkdata_intended_parse(text, len, &intended, err, sizeof err)) {
            fprintf(stderr, "%s: %s: %s\n", me, o.intended.c_str(), err);
            return 1;
        }
        free(text);
    }
    if (!(text = read_all(o.refdata.c_str(), &len))) {
        fprintf(stderr, "%s: cannot read %s\n", me, o.refdata.c_str());
        return 1;
    }
    if (checkdata_ref_parse(text, len, &refdata, err, sizeof err)) {
        fprintf(stderr, "%s: %s: %s\n", me, o.refdata.c_str(), err);
        return 1;
    }
    free(text);
    if (load_read(o.cbuild.c_str(), &c, err, sizeof err)) {
        fprintf(stderr, "%s: %s: %s\n", me, o.cbuild.c_str(), err);
        return 1;
    }
    out = o.quiet ? open_memstream(&report, &reportlen) : stdout;
    if (!out)
        return 1;
    bad = checkdata_run(&table, &refdata, &c, with_intended ? &intended : NULL, o.verbose, out);
    if (o.quiet) {
        fclose(out);
        if (bad)
            fwrite(report, 1, reportlen, stdout);
        free(report);
    }
    load_free(&c);
    checkdata_ref_free(&refdata);
    checkdata_table_free(&table);
    checkdata_intended_free(&intended);
    return bad != 0;
}

struct ref_options {
    std::string table, listing, reference, output;
};

/* the header of the reference data */
static const char ref_header[] =
    "The reference bytes of the checks of refcheck data (tools/lib/checkdata):\n"
    "START<TAB>END label or SIZE<TAB>the bytes in hex, \"..\" not compared (a\n"
    "relocated long). Generated by refcheck data-ref from the reference build;\n"
    "do not edit.";

static int run_ref(const ref_options &o)
{
    struct checkdata_table table;
    struct checkdata_ref refdata;
    struct listing listing;
    struct loadfile ref;
    char err[200];
    std::string tmp = o.output + ".new";
    FILE *out;
    long missing;
    int rc = 0;

    if (read_table(o.table, &table))
        return 1;
    if (listing_read(o.listing.c_str(), &listing, err, sizeof err)) {
        fprintf(stderr, "%s: %s: %s\n", me, o.listing.c_str(), err);
        return 1;
    }
    if (load_read(o.reference.c_str(), &ref, err, sizeof err) || ref.nhunks < 1) {
        fprintf(stderr, "%s: %s: %s\n", me, o.reference.c_str(), ref.nhunks ? err : "no hunk");
        return 1;
    }
    missing = checkdata_ref_make(&table, &listing, &ref.hunks[0], &refdata, stdout);
    if (missing < 0) {
        fprintf(stderr, "%s: out of memory\n", me);
        rc = 1;
    } else if (missing) {
        fprintf(stderr, "%s: %ld ranges of %s not in the listing\n", me, missing, o.table.c_str());
        rc = 1;
    } else if (!(out = fopen(tmp.c_str(), "w"))) {
        fprintf(stderr, "%s: cannot write %s\n", me, tmp.c_str());
        rc = 1;
    } else {
        checkdata_ref_write(&refdata, ref_header, out);
        if (fclose(out) || rename(tmp.c_str(), o.output.c_str())) {
            fprintf(stderr, "%s: cannot write %s\n", me, o.output.c_str());
            remove(tmp.c_str());
            rc = 1;
        }
    }
    if (missing >= 0)
        checkdata_ref_free(&refdata);
    load_free(&ref);
    listing_free(&listing);
    checkdata_table_free(&table);
    return rc;
}

void cmd_data(CLI::App &app, int &status)
{
    auto o = std::make_shared<data_options>();
    CLI::App *sub = app.add_subcommand("data", "data of a C build against the reference data of the assembler original");
    CLI::Option *v = sub->add_flag("-v", o->verbose, "every check");
    sub->add_flag("-q", o->quiet, "the report only if a check failed")->excludes(v);
    sub->add_option("TABLE", o->table, "the checks (e.g. programs/ted/checkdata.tsv)")->required();
    sub->add_option("REFDATA", o->refdata,
                    "the reference data (data-ref, e.g. tests/data/ted-checkdata.txt)")
        ->required();
    sub->add_option("CBUILD", o->cbuild, "the C build with symbols")->required();
    sub->add_option("INTENDED", o->intended,
                    "the checks that differ on purpose (CSYM<TAB>#ISSUE<TAB>NOTE per line), each of "
                    "them must differ");
    sub->footer("Prints the failed checks and a summary. Exit status 0, 1 a check failed, an "
                "INTENDED entry is stale or an input cannot be read, 2 usage error.");
    sub->callback([sub, o, &status] {
        const std::string name = cli::name(*sub);

        me = name.c_str();
        status = run(*o);
    });

    auto r = std::make_shared<ref_options>();
    CLI::App *rsub = app.add_subcommand("data-ref", "the reference data of data from the reference build");
    rsub->add_option("TABLE", r->table, "the checks (e.g. programs/ted/checkdata.tsv)")->required();
    rsub->add_option("LISTING", r->listing, "the vasm listing of the reference build")->required();
    rsub->add_option("REFERENCE", r->reference, "the reference build (a load file)")->required();
    rsub->add_option("-o", r->output, "the reference data to write")->required();
    rsub->footer("Writes the bytes of every range of TABLE. Exit status 0, 1 a label is not in "
                 "the listing (said on stdout) or an input cannot be read, 2 usage error.");
    rsub->callback([rsub, r, &status] {
        static std::string name;

        name = cli::name(*rsub);
        me = name.c_str();
        status = run_ref(*r);
    });
}
